import { test, expect } from '@playwright/test';
import os from 'node:os';
import path from 'node:path';

test('device enrollment, per-device policy, diagnosis queue and manual remediation', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await expect(page).toHaveTitle(/WFI/);
  await page.getByRole('button', { name: 'Demoyu aç' }).click();
  await page.getByRole('button', { name: 'Cihazlar ve AI', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sunucu yapay zekâ modeli' })).toBeVisible();
  const hostname = `qa-${Date.now()}`;
  await page.getByLabel('Yeni cihaz hostname').fill(hostname);
  await page.getByRole('button', { name: 'Cihaz kaydet', exact: true }).click();
  await expect(page.getByLabel('Cihaz kimliği', { exact: true })).not.toBeEmpty();
  await expect(page.getByLabel('Kayıt token’ı')).toHaveAttribute('type', 'password');
  await page.getByRole('button', { name: 'Bilgileri kapat' }).click();
  await page.getByLabel('Ajan cihazı ara').fill(hostname);
  await expect(page.getByRole('button', { name: 'Cihazı aç', exact: true })).toHaveCount(1);
  await page.getByRole('row').filter({ hasText: hostname }).getByRole('button', { name: 'Cihazı aç', exact: true }).click();
  await page.getByRole('button', { name: 'Kayıt token’ını yenile' }).click();
  await expect(page.getByLabel('Kayıt token’ı')).not.toBeEmpty();
  await page.getByRole('button', { name: 'Bilgileri kapat' }).click();
  await page.getByLabel('Cihaz otomatik modu', { exact: true }).selectOption('Disabled');
  await page.getByRole('button', { name: 'Cihaz ayarını kaydet' }).click();
  await expect(page.getByRole('status')).toContainText('Cihaz otomatik modu kaydedildi');
  await page.getByLabel('Otomatik modu etkinleştir', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Genel ayarı kaydet' }).click();
  await expect(page.getByRole('status')).toContainText('Genel otomatik mod kaydedildi');
  await page.getByRole('button', { name: 'Uzaktan teşhis başlat' }).click();
  await expect(page.getByText('FullSystemScan · Bekliyor', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Uzaktan teşhis başlat', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Bu cihazda aktif teşhis var');
  await expect(page.getByText('FullSystemScan · Bekliyor', { exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: 'Teşhisi iptal et', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Teşhis iptal edildi');
  await expect(page.getByText('İstemci tarafından iptal edildi.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Teşhisi iptal et', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Teşhis sonucu', exact: true }).click();
  await expect(page.getByText('Bu teşhis için AI sonucu bulunmuyor.', { exact: false })).toBeVisible();
  await page.getByLabel('Düzeltme işlemi', { exact: true }).selectOption('PB-DNS-FLUSH');
  await page.getByRole('button', { name: 'Seçili düzeltmeyi iste' }).click();
  await expect(page.getByText(/DNS.*Ajan bekleniyor/)).toBeVisible();
  await page.getByRole('button', { name: 'Seçili düzeltmeyi iste' }).click();
  await expect(page.getByRole('alert')).toContainText('aynı düzeltme zaten bekliyor veya çalışıyor');
  await expect(page.getByText(/DNS.*Ajan bekleniyor/)).toHaveCount(1);
  await expect(page.getByText('İşlem doğrulandı', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Bekleyen düzeltmeyi iptal et', exact: true }).click();
  await expect(page.getByText(/DNS.*Başlamadan iptal edildi/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Bekleyen düzeltmeyi iptal et', exact: true })).toHaveCount(0);
  await page.getByLabel('Düzeltme işlemi', { exact: true }).selectOption('PB-DISM-REPAIR');
  await page.getByRole('button', { name: 'Seçili düzeltmeyi iste' }).click();
  await expect(page.getByText('Windows bileşen deposunu onar · Yönetici onayı bekliyor', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Düzeltmeyi onayla', exact: true }).click();
  await expect(page.getByText('Windows bileşen deposunu onar · Ajan bekleniyor', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Düzeltmeyi onayla', exact: true })).toHaveCount(0);
  for (const theme of ['standard', 'light', 'dark']) {
    await page.getByLabel('Tema', { exact: true }).selectOption(theme);
    await page.screenshot({ path: path.join(os.tmpdir(), `wfi-remote-${theme}.png`), fullPage: true });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(os.tmpdir(), 'wfi-remote-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});
